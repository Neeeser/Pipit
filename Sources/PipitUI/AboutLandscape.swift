    /// How high a ridge stands at `x`, both in drawing units.
    static func height(of ridge: [CGPoint], at x: CGFloat) -> CGFloat {
        guard let after = ridge.firstIndex(where: { $0.x >= x }) else {
            return ridge.last?.y ?? 0
        }
        guard after > 0 else { return ridge[after].y }
        let left = ridge[after - 1]
        let right = ridge[after]
        let span = right.x - left.x
        guard span > 0 else { return right.y }
        return left.y + (right.y - left.y) * (x - left.x) / span
    }

    private static func parse(_ text: Substring) -> [CGPoint] {
        text.split(whereSeparator: \.isWhitespace).compactMap { pair in
            let parts = pair.split(separator: ",")
            guard parts.count == 2, let x = Double(parts[0]), let y = Double(parts[1]) else {
                return nil
            }
            return CGPoint(x: x, y: y)
        }
    }

    private static func parse(_ text: String) -> [CGPoint] { parse(text[...]) }

    private static func parseTrees(_ text: String) -> [[CGPoint]] {
        text.split(separator: ";").map(parse).filter { !$0.isEmpty }
    }

