/// One layer: its ridge filled down to the bottom of the frame, and its pines.
struct LayerShape: Shape {
    let layer: AboutLandscape.Layer

    func path(in rect: CGRect) -> Path {
        let scale = rect.width / AboutLandscape.width
        func place(_ point: CGPoint) -> CGPoint {
            CGPoint(x: rect.minX + point.x * scale, y: rect.maxY - point.y * scale)
        }
        var path = Path()
        guard let first = layer.ridge.first, let last = layer.ridge.last else { return path }
        // The website's outlines stop a few units short of the crop's right
        // edge, so the end heights are carried out to both edges.
        path.move(to: CGPoint(x: rect.minX, y: rect.maxY))
        path.addLine(to: CGPoint(x: rect.minX, y: rect.maxY - first.y * scale))
        for point in layer.ridge {
            path.addLine(to: place(point))
        }
        path.addLine(to: CGPoint(x: rect.maxX, y: rect.maxY - last.y * scale))
        path.addLine(to: CGPoint(x: rect.maxX, y: rect.maxY))
        path.closeSubpath()
        for tree in layer.trees {
            path.addLines(tree.map(place))
            path.closeSubpath()
        }
        return path
    }
}
